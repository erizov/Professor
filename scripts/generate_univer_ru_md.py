def get_wikipedia_content(algorithm_name: str) -> Dict[str, str]:
    """Get Wikipedia content for an algorithm."""
    info = {}
    
    try:
        # Common algorithm name mappings
        name_mappings = {
            'bubble sort': 'Bubble_sort',
            'insertion sort': 'Insertion_sort',
            'selection sort': 'Selection_sort',
            'merge sort': 'Merge_sort',
            'quick sort': 'Quicksort',
            'heap sort': 'Heapsort',
            'binary search': 'Binary_search_algorithm',
            'linear search': 'Linear_search',
            'binary tree': 'Binary_tree',
            'hash table': 'Hash_table',
            'depth first search': 'Depth-first_search',
            'breadth first search': 'Breadth-first_search',
            'batch processing': 'Batch_processing',
            'data monitoring': 'Data_monitoring',
            'data quality': 'Data_quality',
            'stream processing': 'Stream_processing',
            'isolation forest': 'Isolation_forest',
            'neural network': 'Artificial_neural_network',
            'decision tree': 'Decision_tree_learning',
            'k-means': 'K-means_clustering',
            'linear regression': 'Linear_regression',
            'logistic regression': 'Logistic_regression',
        }
        
        clean_name = algorithm_name.replace('_', ' ').strip()
        wiki_name = name_mappings.get(clean_name.lower())
        
        if not wiki_name:
            wiki_name = clean_name.title().replace(' ', '_')
        
        # Try to get summary
        variations = [
            wiki_name,
            clean_name.replace(' ', '_'),
            clean_name.replace(' ', '_').title(),
        ]
        
        for variation in variations:
            try:
                url = f"https://en.wikipedia.org/api/rest_v1/page/summary/{variation}"
                with urllib.request.urlopen(url, timeout=5) as response:
                    data = json.loads(response.read().decode('utf-8'))
                    if 'extract' in data and len(data['extract']) > 100:
                        info['summary'] = data['extract']
                        break
            except (URLError, HTTPError, KeyError):
                continue
            except Exception:
                continue
        
    except Exception:
        pass
    
    return info


def determine_discipline(english_name: str, folder_path: Path) -> str:
    """Determine the discipline for the algorithm."""
    lower_name = english_name.lower()
    
    # Check metadata first
    metadata_file = folder_path / "metadata.json"
    if metadata_file.exists():
        try:
            metadata = json.loads(metadata_file.read_text(encoding='utf-8'))
            category = metadata.get('category', '').lower()
            algo_type = metadata.get('algorithm_type', '').lower()
            
            # Check for ML/AI
            if any(x in category or x in algo_type for x in ['ml', 'machine learning', 'ai', 'neural', 'deep learning', 'reinforcement']):
                return 'Machine Learning / AI'
            # Check for Data Engineering
            elif any(x in category or x in algo_type for x in ['data', 'database', 'warehouse', 'lake', 'engineering', 'pipeline', 'batch', 'stream']):
                return 'Data Engineering / Data Governance'
            # Check for Monitoring/Security
            elif any(x in category or x in algo_type for x in ['security', 'monitoring', 'observability', 'ops', 'devops']):
                return 'Monitoring & Security'
            # Check for blockchain/quantum
            elif any(x in category or x in algo_type for x in ['blockchain', 'crypto', 'quantum']):
                return 'Computer Science'
        except:
            pass
    
    # Check folder path for context
    folder_parts = str(folder_path).lower()
    
    # Infer from name and path
    if any(x in lower_name or x in folder_parts for x in ['ml', 'neural', 'learning', 'model', 'training', 'inference', 'ai', 'reinforcement']):
        return 'Machine Learning / AI'
    elif any(x in lower_name or x in folder_parts for x in ['monitoring', 'security', 'audit', 'compliance', 'threat', 'observability']):
        return 'Monitoring & Security'
    elif any(x in lower_name or x in folder_parts for x in ['data', 'quality', 'governance', 'pipeline', 'warehouse', 'lake', 'engineering', 'batch', 'stream']):
        return 'Data Engineering / Data Governance'
    elif any(x in lower_name or x in folder_parts for x in ['blockchain', 'quantum', 'crypto']):
        return 'Computer Science'
    else:
        return 'Computer Science'


def get_algorithm_name(folder_path: Path) -> Tuple[str, str]:
    """Get algorithm name in English and Russian."""
    # Try metadata
    metadata_file = folder_path / "metadata.json"
    english_name = None
    if metadata_file.exists():
        try:
            metadata = json.loads(metadata_file.read_text(encoding='utf-8'))
            if 'name' in metadata:
                english_name = metadata['name']
            elif 'display_name' in metadata:
                english_name = metadata['display_name']
        except:
            pass
    
    # Try README
    if not english_name:
        readme_file = folder_path / "README.md"
        if readme_file.exists():
            try:
                content = readme_file.read_text(encoding='utf-8')
                first_line = content.split('\n')[0].strip()
                if first_line.startswith('#'):
                    english_name = first_line.lstrip('#').strip()
            except:
                pass
    
    # Fallback
    if not english_name:
        english_name = folder_path.name.replace('_', ' ').title()
    
    # Get Russian name from school.ru.md if exists
    school_file = folder_path / "school.ru.md"
    russian_name = english_name
    if school_file.exists():
        try:
            content = school_file.read_text(encoding='utf-8')
            title_match = re.search(r'^# (.+)$', content, re.MULTILINE)
            if title_match:
                russian_name = title_match.group(1).strip()
        except:
            pass
    
    # Fix mixed English-Russian names
    if russian_name.startswith('Decision') or russian_name.startswith('Neural') or russian_name.startswith('Batch'):
        # Translate common patterns
        translations = {
            'Decision Дерево': 'Дерево решений',
            'Decision Tree': 'Дерево решений',
            'Neural Network Basics': 'Нейронные сети (основы)',
            'Neural Network': 'Нейронные сети',
            'Batch Processing Advanced': 'Продвинутая батч-обработка',
        }
        russian_name = translations.get(russian_name, russian_name)
    
    return english_name, russian_name


